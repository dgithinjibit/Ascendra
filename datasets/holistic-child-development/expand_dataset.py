def main() -> int:
    rows = [json.loads(line) for line in DATASET.read_text().splitlines() if line.strip()]
    defaults = {
        "source_principles": ["syncsenta_holistic_development_seed"],
        "learning_objective": "support holistic development through safe, learner-centred practice",
        "localization_notes": "Adapt with educators and communities; do not assume one cultural context is universal.",
        "accessibility_notes": "Offer multiple ways to understand and respond.",
        "adult_support_route": "trusted_adult_if_needed",
        "license": "CC-BY-4.0",
    }
    for row in rows:
        for key, value in defaults.items():
            row.setdefault(key, value)
    existing_ids = {row["id"] for row in rows}
    rows.extend(record for record in NEW_RECORDS if record["id"] not in existing_ids)
    DATASET.write_text("\n".join(json.dumps(row, ensure_ascii=False, separators=(",", ":")) for row in rows) + "\n")
    print(f"wrote {len(rows)} records, including {len(NEW_RECORDS)} AI-wellbeing scenarios")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
